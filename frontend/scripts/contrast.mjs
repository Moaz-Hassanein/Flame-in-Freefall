// WCAG 2.x contrast check for the text/background pairs used in styles.css.
// Run: npm run contrast  (writes ../docs/PHASE10_CONTRAST.md and exits 1 if any pair < required)
import { writeFileSync, mkdirSync } from 'node:fs';

const lum = (hex) => {
  const c = hex.replace('#', '');
  const [r, g, b] = [0, 2, 4].map((i) => parseInt(c.slice(i, i + 2), 16) / 255).map((v) => (v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};
const ratio = (a, b) => {
  const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p);
  return (x + 0.05) / (y + 0.05);
};

const themes = {
  'dark / space': { bg: '#050816', bg2: '#0B1026', panel: '#101A33', hover: '#172443', ink: '#F4F7FF', mute: '#91A4C5', cyan: '#36D9FF', warn: '#FF9B54', err: '#FF5364', model: '#B4A9FF', btnA: '#1F63D6', btnB: '#5B49D8' },
  'light / space': { bg: '#eef2fb', bg2: '#e2e9f8', panel: '#ffffff', hover: '#f1f5ff', ink: '#0B1026', mute: '#46587a', cyan: '#06708a', warn: '#a84a08', err: '#b3182b', model: '#5b45d6', btnA: '#1F63D6', btnB: '#5B49D8' },
  'dark / blue': { bg: '#050816', bg2: '#0B1026', panel: '#101A33', hover: '#172443', ink: '#F4F7FF', mute: '#91A4C5', cyan: '#36D9FF', warn: '#8CC4FF', err: '#B9D6FF', model: '#9DB8FF', btnA: '#1F63D6', btnB: '#5B49D8' },
  'light / blue': { bg: '#eef2fb', bg2: '#e2e9f8', panel: '#ffffff', hover: '#f1f5ff', ink: '#0B1026', mute: '#46587a', cyan: '#06708a', warn: '#1b4fa8', err: '#0f3a86', model: '#2a4cc0', btnA: '#1F63D6', btnB: '#5B49D8' },
};

const pairs = (t) => [
  ['Body text on page', t.ink, t.bg],
  ['Body text on panel', t.ink, t.panel],
  ['Muted text on panel', t.mute, t.panel],
  ['Muted text on page', t.mute, t.bg],
  ['Muted text on panel hover', t.mute, t.hover],
  ['Muted text on inset (bg2)', t.mute, t.bg2],
  ['Link / accent (cyan) on panel', t.cyan, t.panel],
  ['Link / accent (cyan) on page', t.cyan, t.bg],
  ['Warning / flag text on panel', t.warn, t.panel],
  ['Error text on panel', t.err, t.panel],
  ['Modeled text on panel', t.model, t.panel],
  ['Button text on gradient start', '#ffffff', t.btnA],
  ['Button text on gradient end', '#ffffff', t.btnB],
];

let fail = 0;
let md = '# Phase 10 contrast report (WCAG 2.x AA)\n\nNormal text needs 4.5:1. Generated by `npm run contrast`.\n';
for (const [name, t] of Object.entries(themes)) {
  md += `\n## ${name}\n\n| Pair | Ratio | AA |\n|---|---|---|\n`;
  for (const [label, fg, bg] of pairs(t)) {
    const r = ratio(fg, bg);
    const ok = r >= 4.5;
    if (!ok) fail++;
    md += `| ${label} (${fg} on ${bg}) | ${r.toFixed(2)} | ${ok ? 'pass' : 'FAIL'} |\n`;
  }
}
mkdirSync('../docs', { recursive: true });
writeFileSync('../docs/PHASE10_CONTRAST.md', md);
console.log(md);
console.log(fail ? `${fail} pair(s) FAIL` : 'All pairs pass AA');
process.exit(fail ? 1 : 0);
